@file:OptIn(kotlinx.cinterop.ExperimentalForeignApi::class)

package com.flyfishxu.kadb

import com.flyfishxu.kadb.cert.InMemoryPrivateKeyStore
import com.flyfishxu.kadb.cert.KadbCert
import kotlinx.cinterop.toKString
import kotlinx.coroutines.runBlocking
import okio.Buffer
import okio.ByteString.Companion.toByteString
import platform.Foundation.NSUUID
import platform.posix.getenv
import platform.posix.unsetenv
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue
import kotlin.time.Clock

class RealDeviceSmokeTest {
    /** Explicitly opted in via KADB_DEVICE_* variables; never discovers or changes unrelated devices. */
    @Test fun pairConnectShellTransferAndReconnect() {
        val host = environment("KADB_DEVICE_HOST") ?: run {
            println("SKIP: real Android device smoke test was not requested")
            return
        }
        val pairingPort = requireNotNull(environment("KADB_PAIRING_PORT")) { "Missing pairing port" }.toInt()
        val pairingCode = requireNotNull(environment("KADB_PAIRING_CODE")) { "Missing pairing code" }
        val connectPort = requireNotNull(environment("KADB_CONNECT_PORT")) { "Missing connection port" }.toInt()
        listOf("KADB_DEVICE_HOST", "KADB_PAIRING_PORT", "KADB_PAIRING_CODE", "KADB_CONNECT_PORT").forEach { unsetenv(it) }
        require(host.isNotBlank() && '\u0000' !in host) { "Invalid device host" }
        require(pairingPort in 1..65535 && connectPort in 1..65535) { "Invalid device port" }
        require(pairingCode.length == 6 && pairingCode.all(Char::isDigit)) { "Invalid pairing code format" }

        // No key store path is configured: this test identity exists only in this process's memory.
        KadbCert.configure(InMemoryPrivateKeyStore())
        val remotePath = "/data/local/tmp/kadb-ios-smoke-${NSUUID().UUIDString}.bin"
        var client: Kadb? = null
        var primaryFailure: Throwable? = null
        var createdRemoteFile = false
        try {
            println("Running real-device pairing from the iOS Kotlin client")
            runBlocking { Kadb.pair(host, pairingPort, pairingCode, name = "Kadb iOS smoke test") }
            println("PASS: pairing over iOS TLS and SPAKE2")
            val active = Kadb.create(host, connectPort, connectTimeout = 10_000, socketTimeout = 15_000)
            client = active
            checkShell(active, "initial")
            val shellV2 = active.supportsFeature("shell_v2")
            if (shellV2) {
                val response = active.shell("printf 'stdout'; printf 'stderr' >&2; exit 7")
                assertEquals("stdout", response.output)
                assertEquals("stderr", response.errorOutput)
                assertEquals(7, response.exitCode)
            }
            println("PASS: ADB TLS connection and shell; shell_v2=$shellV2")

            val payload = ByteArray(1024 * 1024 + 13) { index -> ((index * 31) xor (index ushr 8)).toByte() }
            val expectedHash = payload.toByteString().sha256().hex()
            createdRemoteFile = true // A failed transfer may have created a partial file.
            active.push(Buffer().write(payload), remotePath, mode = 0x180,
                lastModifiedMs = Clock.System.now().toEpochMilliseconds())
            val downloaded = Buffer()
            active.pull(downloaded, remotePath)
            assertEquals(payload.size.toLong(), downloaded.size, "Downloaded file size differs")
            assertEquals(expectedHash, downloaded.readByteString().sha256().hex(), "Downloaded content differs")
            println("PASS: ${payload.size} byte binary push/pull with matching SHA-256")

            repeat(2) { index ->
                active.resetConnection()
                assertFalse(active.connectionCheck(), "Reset should release the existing connection")
                checkShell(active, "reconnect-$index")
            }
            println("PASS: two resets and authenticated reconnections")
        } catch (error: Throwable) {
            primaryFailure = error
            throw error
        } finally {
            try {
                if (createdRemoteFile) {
                    // The path is generated by this test and contains only UUID/path characters.
                    val cleanup = requireNotNull(client).shell("rm -f '$remotePath' && test ! -e '$remotePath' && printf 'kadb-ios-clean'")
                    assertEquals(0, cleanup.exitCode, "Could not remove the smoke test's temporary file")
                    assertEquals("kadb-ios-clean", cleanup.output, "Temporary-file cleanup was not confirmed")
                    println("PASS: removed the smoke test's temporary file")
                }
            } catch (cleanupError: Throwable) {
                if (primaryFailure != null) primaryFailure.addSuppressed(cleanupError) else throw cleanupError
            } finally {
                client?.close()
                KadbCert.clear()
            }
        }
    }

    private fun checkShell(client: Kadb, marker: String) {
        val expected = "kadb-ios-$marker"
        val response = client.shell("printf '$expected'")
        assertEquals(expected, response.output)
        assertEquals("", response.errorOutput)
        assertEquals(0, response.exitCode)
        assertTrue(client.connectionCheck())
    }

    private fun environment(name: String): String? = getenv(name)?.toKString()
}
